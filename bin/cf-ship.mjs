#!/usr/bin/env node
// cf-ship — build & deploy Cloudflare Workers (pure SPA) with one command.
//
// ⚠️ NODE.JS ONLY — this is a build/deployment helper, never import it from
// browser or Worker code.
//
// Purpose: projects that install the web-cloudflare package get the wrangler
// CLI as a transitive dependency, so a fleet of SPAs can deploy with:
//
//   npm install -D @umituz/web-cloudflare
//   npx cf-ship init      # generates wrangler.jsonc (assets-only SPA Worker)
//   npx cf-ship deploy    # npm run build + wrangler deploy
//
// No project installs or pins wrangler itself — the shared package owns it.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const USAGE = `cf-ship — build & deploy Cloudflare Workers (pure SPA) with one command

Usage:
  cf-ship init [--name <name>] [--assets-dir <dir>]
      Generate wrangler.jsonc for an assets-only SPA Worker (skips if one exists).
      --name       Worker name (default: package.json name without scope)
      --assets-dir Build output directory (default: ./dist, or ./build if only it exists)
  cf-ship deploy [--skip-build] [...wrangler args]
      Run the project's build script, then \`wrangler deploy\`.
  cf-ship login | logout | whoami | dev | tail
      Pass through to the bundled wrangler CLI.
  cf-ship <anything else>
      Pass through to the bundled wrangler CLI (kv, r2, d1, secret, ...).

Wrangler is resolved from the shared package's node_modules — projects never
install it themselves. Environment auth (CLOUDFLARE_API_TOKEN) is respected.`;

/** Render an assets-only Worker config (pure SPA, no worker script). */
export function renderWranglerConfig({ name, assetsDirectory = './dist' }) {
  // JSON.stringify handles quoting/escaping of interpolated values.
  return `{
  "$schema": "node_modules/wrangler/config-schema.json",
  // Generated by \`cf-ship init\` — assets-only Worker (pure SPA, no worker script).
  // "single-page-application" serves index.html for unknown paths, so client-side
  // routing (BrowserRouter) survives refresh and deep links.
  // When a backend lands, add "main" + API routes to this same Worker (same origin).
  "name": ${JSON.stringify(name)},
  "compatibility_date": "2025-09-01",
  "assets": {
    "directory": ${JSON.stringify(assetsDirectory)},
    "not_found_handling": "single-page-application"
  }
}
`;
}

/** Minimal `--flag` / `--option value` parser. */
export function parseArgs(argv) {
  const positionals = [];
  const flags = new Set();
  const options = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--') {
      positionals.push(...argv.slice(i + 1));
      break;
    }
    if (arg.startsWith('--')) {
      const value = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[(i += 1)] : undefined;
      const key = arg.slice(2);
      if (value === undefined) flags.add(key);
      else options[key] = value;
    } else {
      positionals.push(arg);
    }
  }
  return { positionals, flags, options };
}

/**
 * Locate the wrangler bin shipped with this package (hoisted or nested).
 * Walks up from `fromDir` looking for node_modules/wrangler — works under
 * npm, yarn and pnpm installs. Returns null when not installed.
 */
export function resolveWranglerBin(fromDir = here) {
  let dir = resolve(fromDir);
  for (;;) {
    const pkgPath = join(dir, 'node_modules', 'wrangler', 'package.json');
    if (existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
        const bin = pkg.bin?.wrangler ?? 'bin/wrangler.js';
        return join(dir, 'node_modules', 'wrangler', bin);
      } catch {
        return null;
      }
    }
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function runWrangler(args) {
  const bin = resolveWranglerBin();
  // Run the resolved bin with node — deterministic across shells and Windows.
  const result = bin
    ? spawnSync(process.execPath, [bin, ...args], { stdio: 'inherit', env: process.env })
    : spawnSync('npx', ['--yes', 'wrangler@4', ...args], {
        stdio: 'inherit',
        env: process.env,
        shell: process.platform === 'win32',
      });
  return result.status ?? 1;
}

function readProjectName(cwd) {
  try {
    const pkg = JSON.parse(readFileSync(join(cwd, 'package.json'), 'utf8'));
    if (pkg.name) return pkg.name.replace(/^@[^/]+\//, '');
  } catch {
    // no package.json — fall through to directory name
  }
  return basename(cwd);
}

function cmdInit({ options }, cwd = process.cwd()) {
  for (const existing of ['wrangler.jsonc', 'wrangler.json', 'wrangler.toml']) {
    if (existsSync(join(cwd, existing))) {
      console.log(`Found existing ${existing} — leaving it untouched.`);
      return 0;
    }
  }

  const name = options.name || readProjectName(cwd);
  let assetsDirectory = options['assets-dir'] || './dist';
  if (!options['assets-dir'] && !existsSync(join(cwd, 'dist')) && existsSync(join(cwd, 'build'))) {
    assetsDirectory = './build';
  }

  writeFileSync(join(cwd, 'wrangler.jsonc'), renderWranglerConfig({ name, assetsDirectory }));
  console.log(`Created wrangler.jsonc (Worker "${name}", assets ${assetsDirectory}).`);
  console.log('Next: add "deploy": "cf-ship deploy" to package.json scripts, then `npm run deploy`.');
  return 0;
}

function cmdDeploy({ flags, positionals }) {
  if (!flags.has('skip-build')) {
    try {
      const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
      if (pkg.scripts?.build) {
        console.log('Running build...');
        const build = spawnSync('npm', ['run', 'build'], {
          stdio: 'inherit',
          env: process.env,
          shell: process.platform === 'win32',
        });
        if (build.status !== 0) return build.status ?? 1;
      }
    } catch {
      console.warn('No package.json found — skipping build step.');
    }
  }
  return runWrangler(['deploy', ...positionals]);
}

export function main(argv = process.argv.slice(2)) {
  const [command, ...rest] = argv;
  const args = parseArgs(rest);

  switch (command) {
    case undefined:
    case 'help':
    case '--help':
    case '-h':
      console.log(USAGE);
      return 0;
    case 'init':
      return cmdInit(args);
    case 'deploy':
      return cmdDeploy(args);
    default:
      // Escape hatch: forward everything (kv, r2, d1, secret, versions, ...).
      return runWrangler(argv);
  }
}

// Run only when executed as a script (not when imported by tests). Compare
// real paths: npm/yarn/pnpm expose this file through node_modules/.bin
// symlinks, so process.argv[1] differs lexically from import.meta.url.
const invokedDirectly = (() => {
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
})();
if (invokedDirectly) {
  process.exitCode = main();
}
